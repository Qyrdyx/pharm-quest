/* 药理闯关 · 掌握度热力图 */
import { PG, reg } from "../core/registry.js";
import { $, TT, clamp, esc, reduceMotion } from "../core/utils.js";
import { DM, G, GM, P } from "../data/index.js";
import { mastery, masteryOf, poolGroups, save, sel } from "../core/state.js";
import { packTag } from "../data/packs.js";
import { SFX } from "../music/sfx.js";
import { ioSheet } from "../records/backup.js";

reg({ mColor: () => mColor, weakest: () => weakest, groupDrugs: () => groupDrugs, renderMastery: () => renderMastery });

/* ---------- 掌握度热力图 ---------- */
export function mColor(m) {
  if (m == null) return "var(--bench-2)";
  const h = m < 0.6 ? 350 + clamp((m - 0.3) / 0.3, 0, 1) * 52 : 42 + clamp((m - 0.6) / 0.3, 0, 1) * 116;
  return `hsl(${Math.round(h % 360)} 62% 42%)`;
}
export function weakest(n = 5) {
  const gs = sel.size ? poolGroups() : G;
  return gs.slice().sort((x, y) => (masteryOf(x.id) ?? 0.45) - (masteryOf(y.id) ?? 0.45)).slice(0, n);
}
export function groupDrugs(gs) { return gs.flatMap(g => g.drugs.map(a => DM.get(a[0]))); }
export function renderMastery(body) {
  const done = G.filter(g => mastery[g.id]?.a).length;
  const avgs = G.map(g => masteryOf(g.id)).filter(x => x != null);
  const avg = avgs.length ? Math.round(avgs.reduce((a, b) => a + b, 0) / avgs.length * 100) : 0;
  const wk = weakest();
  body.innerHTML = `<div class="scope" style="margin-top:6px">
      <div><div class="big">${done}<span style="font-size:15px;color:var(--mute)"> / ${G.length}</span></div><div class="lbl">练过的药物组</div></div>
      <div><div class="big">${avgs.length ? avg + "%" : "—"}</div><div class="lbl">平均掌握度</div></div>
      <div class="chips-mini"><span>当前最弱：</span>${wk.map(g => `<span>#${g.dot || g.id} ${esc(g.n)} ${masteryOf(g.id) == null ? "（未练）" : Math.round(masteryOf(g.id) * 100) + "%"}</span>`).join("")}</div>
      <button class="btn red" id="wkPrac">专练最弱 5 组</button></div>
    <div class="hm-legend"><span>未练</span><i style="background:var(--bench-2)"></i><span>弱</span><i style="background:${mColor(.3)}"></i><i style="background:${mColor(.5)}"></i><i style="background:${mColor(.65)}"></i><i style="background:${mColor(.8)}"></i><i style="background:${mColor(.95)}"></i><span>强</span>
      <span style="margin-left:auto">灰掉的组不在本次考试范围</span></div>
    <div id="hm">${P.chapters.map(c => `<div class="hm-ch"><div class="hm-h"><b>${c[0]}</b> ${esc(c[1])}</div><div class="hm-row">${G.filter(g => g.ch === c[0]).map(g => {
      const m = masteryOf(g.id), st = mastery[g.id];
      return `<button class="hcell ${sel.has(g.id) ? "" : "off"}${PG.isShiny(g) ? " shiny t" + PG.shinyTier(g) : ""}" data-g="${g.id}" style="background:${mColor(m)}">${packTag(g)}<span class="i">#${g.dot || g.id}</span><span class="n">${esc(g.n)}</span><span class="p">${m == null ? "—" : Math.round(m * 100) + "%"}</span><span class="a">${st?.a || 0} 题</span></button>`;
    }).join("")}</div></div>`).join("")}</div>
    <div id="hmd"></div>
    <p class="foot">掌握度 = （答对数 + 1）÷（作答数 + 2）：答得少时会向 50% 收拢，避免答对 1 题就显示 100%。四种玩法的作答都会计入。
      <button class="ibtn" id="mReset" style="margin-left:8px">重置掌握度</button></p>
    <div class="io-row"><button class="ibtn" id="mExp">${TT("导出热力图", "Export heatmap")}</button><button class="ibtn" id="mImp">${TT("导入热力图", "Import heatmap")}</button>
      <span style="font-size:12px;color:var(--mute)">${TT("换设备或清缓存前先导出；导入时与本机记录合并。", "Export before switching devices or clearing data; importing merges with this device.")}</span></div>`;
  $("#wkPrac").onclick = () => { SFX.click(); PG.startQuiz(groupDrugs(weakest())); };
  $("#mExp").onclick = () => { SFX.click(); ioSheet("mastery", "export"); };
  $("#mImp").onclick = () => { SFX.click(); ioSheet("mastery", "import", () => PG.codex("mastery")); };
  body.querySelectorAll(".hcell").forEach(b => b.onclick = () => {
    SFX.pick(); const g = GM.get(+b.dataset.g), st = mastery[g.id], m = masteryOf(g.id);
    body.querySelectorAll(".hcell").forEach(x => x.classList.toggle("cur", x === b));
    $("#hmd").innerHTML = `<div class="explain"><span class="gchip">#${g.dot || g.id} ${esc(g.n)} · ${esc(g.e)}</span>${packTag(g)}${g.ai ? `<p class="pk-warn" style="margin:6px 0 0;font-size:13px">${TT("这一组是 AI 生成的，还没有人工核对，内容以讲义为准。", "This group was generated by AI and hasn't been checked; your notes take precedence.")}</p>` : ""}
      <p>作答 <b>${st?.a || 0}</b> 次，答对 <b>${st?.c || 0}</b> 次，掌握度 <b>${m == null ? "未练" : Math.round(m * 100) + "%"}</b>${st?.t ? `，最近练习 ${new Date(st.t).toLocaleDateString()}` : ""}</p>
      <p class="m">${g.drugs.map(a => esc(a[1]) + (LANG === "en" ? "" : " " + esc(a[2]))).join("、")}</p>
      <div class="q-actions" style="justify-content:flex-start"><button class="btn" id="hmP">只练这一组</button></div></div>`;
    $("#hmP").onclick = () => { SFX.click(); PG.startQuiz(groupDrugs([g])); };
    $("#hmd").scrollIntoView({ behavior: reduceMotion ? "auto" : "smooth", block: "nearest" });
  });
  const rs = $("#mReset");
  rs.onclick = () => {
    if (rs.dataset.armed) { PG.mastery = {}; save(); PG.codex("mastery"); }
    else { rs.dataset.armed = 1; rs.textContent = "再点一次确认重置"; setTimeout(() => { if (rs.isConnected) { delete rs.dataset.armed; rs.textContent = "重置掌握度"; } }, 3000); }
  };
}
